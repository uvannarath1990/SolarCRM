<?php
declare(strict_types=1);

/**
 * Append an immutable entry to audit_log.
 * The DB user for the app must have INSERT + SELECT only on this table.
 */
function writeAuditLog(
    ?int    $leadId,
    string  $action,
    string  $entity,
    string  $fieldName,
    mixed   $oldValue,
    mixed   $newValue
): void {
    $pdo  = getPdo();
    $stmt = $pdo->prepare(
        'INSERT INTO `audit_log`
            (`lead_id`,`user_id`,`action`,`entity`,`field_name`,`old_value`,`new_value`,`ip_address`,`user_agent`,`created_at`)
         VALUES
            (?,?,?,?,?,?,?,?,?,NOW())'
    );
    $stmt->execute([
        $leadId,
        $_SESSION['user_id'] ?? null,
        $action,
        $entity,
        $fieldName,
        $oldValue !== null ? (string) $oldValue : null,
        $newValue !== null ? (string) $newValue : null,
        $_SERVER['REMOTE_ADDR'] ?? null,
        substr($_SERVER['HTTP_USER_AGENT'] ?? '', 0, 255),
    ]);
}

function auditCreate(int $leadId, string $summary): void
{
    writeAuditLog($leadId, 'CREATE', 'lead', 'lead', null, $summary);
}

function auditUpdate(int $leadId, string $field, mixed $old, mixed $new): void
{
    writeAuditLog($leadId, 'UPDATE', 'lead', $field, $old, $new);
}

function auditStageChange(int $leadId, string $from, string $to): void
{
    writeAuditLog($leadId, 'STAGE_CHANGE', 'lead', 'stage', $from, $to);
}

function auditSiteVisit(int $leadId, string $event, string $detail): void
{
    writeAuditLog($leadId, $event, 'site_visit', 'site_visit', null, $detail);
}

function auditLogin(string $email): void
{
    writeAuditLog(null, 'LOGIN', 'user', 'login', null, $email);
}

function auditTaskUpdate(int $taskId, int $leadId, string $field, mixed $old, mixed $new): void
{
    writeAuditLog($leadId, 'TASK_UPDATE', 'workflow_task:' . $taskId, $field, $old, $new);
}

/**
 * Record that a task was created, and who created it.
 *
 * Kept distinct from TASK_UPDATE so creations can be filtered on their own —
 * this is what tells you whether a duplicate was generated by the workflow
 * engine or clicked into existence by a person.
 */
function auditTaskCreate(int $taskId, int $leadId, string $title, ?string $source = null): void
{
    writeAuditLog(
        $leadId,
        'TASK_CREATE',
        'workflow_task:' . $taskId,
        'created',
        $source,
        $title
    );
}

/**
 * Configuration changes that are not tied to a lead — lead sources and the like.
 * lead_id is null, so these never pollute a lead's own history but remain
 * queryable as a config-change log.
 */
function auditConfig(string $action, string $entity, string $field, mixed $old, mixed $new): void
{
    writeAuditLog(null, $action, $entity, $field, $old, $new);
}
